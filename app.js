function NumInput({ value, onChange, min, max, step = 1 }) {
    const [text, setText] = useState(fmt(value));
    const [focused, setFocused] = useState(false);
    useEffect(() => { if (!focused)
        setText(fmt(value)); }, [value, focused]);
    return (React.createElement("input", { type: "text", inputMode: "numeric", value: text, onFocus: () => { setFocused(true); setText(""); }, onChange: (e) => {
            const raw = e.target.value.replace(/[^0-9]/g, "");
            setText(raw === "" ? "" : Number(raw).toLocaleString("th-TH"));
        }, onBlur: () => {
            setFocused(false);
            let num = text === "" ? 0 : parseInt(text.replace(/,/g, ""), 10);
            if (min !== undefined)
                num = Math.max(min, num);
            if (max !== undefined)
                num = Math.min(max, num);
            onChange(num);
            setText(fmt(num));
        }, onKeyDown: (e) => { if (e.key === "Enter")
            e.target.blur(); }, enterKeyHint: "done", className: "w-full rounded-xl border px-3 py-2.5 text-[24px] font-medium", style: { borderColor: "#D7E8F0", color: BRAND.navy } }));
}
