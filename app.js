        const termChild = 21 - age;
        const termPayor = 65 - csPayorAge;
        const csDuration = Math.min(termMain, termChild, termPayor);
        if (csDuration < 2)
            return { ok: false, msg: "ระยะเวลาคุ้มครองที่คำนวณได้ต่ำกว่าเกณฑ์ขั้นต่ำ 2 ปี ไม่สามารถซื้อ คช. ได้ในเงื่อนไขปัจจุบัน" };
        const bi = bandIndex(csPayorAge, CS_BANDS);
        const table = csPayorGender === "female" ? CS_FEMALE : CS_MALE;
        const durIdx = csDuration - 2;
        if (durIdx < 0 || durIdx > 19)
            return { ok: false, msg: "ระยะเวลาคุ้มครอง 2-21 ปี" };
        const rate = table[durIdx][bi];
        if (rate === null || rate === undefined)
            return { ok: false, msg: "ช่วงอายุ/ระยะเวลานี้เกินเงื่อนไขคุ้มครองสูงสุดถึงอายุ 65 ปีของผู้ปกครอง" };
