    function grandTotal() {
        let sum = 0;
        for (const p of PRODUCTS) {
            if (p.id === "CS")
                continue;
            if (!selected[p.id])
                continue;
            const r = CALC[p.id]();
            if (r.ok && r.premium)
                sum += r.premium;
        }
        return sum;
    }
