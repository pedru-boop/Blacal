    function happypensionRow(term) {
        const pct = HAPPYPENSION_PENSION_PCT[term];
        const maxAge = HAPPYPENSION_MAX_AGE_BY_TERM[term];
        const minSI = HAPPYPENSION_MIN_SI_BY_TERM[term];
        const ti = HAPPYPENSION_TERMS.indexOf(term);
        const label = HAPPYPENSION_TERM_LABELS[term];
        let ok = true, msg = "";
        if (age < 20 || age > maxAge) {
            ok = false;
            msg = `อายุรับประกัน 20-${maxAge} ปี`;
        }
        let effectiveSI = 0, premium = 0, discount = 0;
        if (ok) {
            const idx = age - 20;
            const rate = (gender === "female" ? HAPPYPENSION_FEMALE : HAPPYPENSION_MALE)[idx][ti];
            if (rate === null) {
                ok = false;
                msg = "ไม่มีอัตราเบี้ยช่วงอายุนี้";
            }
            else if (happypensionMode === "pension") {
                effectiveSI = happypensionTargetPension > 0 ? happypensionTargetPension / pct : 0;
                if (term === "to60") {
                    if (effectiveSI >= 500000)
                        discount = 0.10;
                    else if (effectiveSI >= 300000)
                        discount = 0.05;
                }
                premium = ((rate * effectiveSI) / 1000) * (1 - discount);
            }
            else {
                // โหมดกรอกเบี้ยประกัน: คำนวณย้อนกลับหาทุนประกันภัยจากงบเบี้ยที่ตั้งไว้
                const budget = happypensionPremiumInput;
                if (budget <= 0) {
                    effectiveSI = 0;
                }
                else if (term === "to60") {
                    const bands = [{ lo: 0, hi: 300000, d: 0 }, { lo: 300000, hi: 500000, d: 0.05 }, { lo: 500000, hi: Infinity, d: 0.10 }];
                    let found = null;
                    for (const b of bands) {
                        const si = (budget * 1000) / (rate * (1 - b.d));
                        if (si >= b.lo && si < b.hi) {
                            found = { si, d: b.d };
                            break;
                        }
                    }
                    if (!found) {
                        const b = bands[bands.length - 1];
                        found = { si: (budget * 1000) / (rate * (1 - b.d)), d: b.d };
                    }
                    effectiveSI = found.si;
                    discount = found.d;
                }
                else {
                    effectiveSI = (budget * 1000) / rate;
                }
                premium = budget;
            }
            if (effectiveSI <= 0) {
                ok = false;
                msg = "กรุณากรอกจำนวนเงิน";
            }
            else if (effectiveSI < minSI) {
                ok = false;
                msg = `ทุนที่คำนวณได้ต่ำกว่าขั้นต่ำ ${baht(minSI)} บาท`;
            }
        }
        const pension = ok ? effectiveSI * pct : 0;
        const pensionYears = 39; // จ่ายบำนาญตั้งแต่อายุครบ 60 ถึงก่อนอายุครบ 99 ปี = 39 ปี
        const totalPensionPaid = pension * pensionYears;
        const premiumYears = term === "once" ? 1 : term === "5y" ? 5 : term === "10y" ? 10 : Math.max(1, 60 - age);
        const totalPremium = ok ? premium * premiumYears : 0;
        return { term, label, effectiveSI, premium, premiumYears, totalPremium, pension, pensionYears, totalPensionPaid, pct, ok, msg, discount };
    }
